'use strict'

/**
 * build-paginator — 把卡片分页决策层打成 **IIFE** 字符串产物（P2-2）
 *
 * ## 为什么必须"构建期打包"而不是"运行时 require"
 *
 * `card-paginator-core.js` 要被**注入到渲染进程**里跑（设计文 §7.7「注入策略 A」：
 * offscreen 窗口 + 注入脚本 + capturePage）。而渲染进程拿不到 main 的模块系统。
 *
 * 三条路，只有一条对：
 *
 * | 路 | 问题 |
 * |---|---|
 * | 运行时 `require('esbuild')` 现打 | **`esbuild` 在 `apps/desktop` 是 devDependency**（V-20 已核实）⇒ 打包产物里没有它 |
 * | **复制源码进注入脚本** | 算法**两份实现** ⇒ 迟早漂移，且漂移了没人发现（注入脚本没有测试覆盖） |
 * | **构建期 esbuild 打包** ✅ | 算法**只有一份实现**，产物是构建结果 |
 *
 * 本脚本走第三条。
 *
 * ## 与 build-preload.js 的关系
 *
 * 形态**刻意照抄** `scripts/build-preload.js`（同目录既有先例）：同样的 esbuild 选项骨架、
 * 同样导出 build 函数与路径常量（**可测**）、同样 `if (require.main === module) main()`。
 * 差别只有两处，都是本任务的性质决定的：
 *
 *   1. `format: 'iife'`（preload 是 `'cjs'`）—— 产物要被 `buildEvalScript` 注入执行，
 *      需要一个**立即执行**的表达式，不能是 CommonJS 模块
 *   2. `globalName: '__cardPaginator'` —— 注入后要能**取到导出**
 *
 * ## 产物是否入库
 *
 * **入库**（与 `electron/preload/index.bundle.js` 同形态）。理由：AGENTS.md 的
 * 「修改 `electron/preload/page-manager.js` 必须重打包 `index.bundle.js`（bundle 断言拦截遗漏）」
 * 把 bundle 当作**受管产物**；`app.asar` 里的路径必须真实存在，不能依赖"构建时恰好跑过"。
 * 产物带 `// @generated` 头，且本脚本的测试会断言"重新构建后字节一致"（防手工编辑）。
 */

const path = require('path')
const esbuild = require('esbuild')

const DESKTOP_ROOT = path.resolve(__dirname, '..')
const REPO_ROOT = path.resolve(DESKTOP_ROOT, '..', '..')

/** 源：决策层唯一实现 */
const ENTRY_FILE = path.join(REPO_ROOT, 'packages', 'shared-utils', 'src', 'card-paginator-core.js')
/** 产物：落在 electron/** 下（打包时随 app.asar 一起进包） */
const OUTPUT_FILE = path.join(DESKTOP_ROOT, 'electron', 'services', 'generated', 'card-paginator.iife.js')

/** 注入后取导出的全局名 */
const GLOBAL_NAME = '__cardPaginator'

/**
 * 产物头部。**不要手改产物** —— 测试会断言"重新构建后字节一致"。
 * `@generated` 是给人和工具看的标记。
 */
const BANNER = [
  '// @generated by apps/desktop/scripts/build-paginator.js — 请勿手改',
  '// 源: packages/shared-utils/src/card-paginator-core.js',
  '// 重新生成: pnpm run build:paginator（在 apps/desktop 下）',
].join('\n')

/**
 * 构建 IIFE 产物。
 *
 * @param {{ write?: boolean, logLevel?: string }} [opts]
 * @returns {Promise<import('esbuild').BuildResult>}
 */
function buildPaginator ({ write = true, logLevel = 'silent' } = {}) {
  return esbuild.build({
    absWorkingDir: DESKTOP_ROOT,
    entryPoints: [ENTRY_FILE],
    outfile: OUTPUT_FILE,
    bundle: true,
    platform: 'browser',
    format: 'iife',
    globalName: GLOBAL_NAME,
    target: 'chrome120',
    legalComments: 'none',
    charset: 'utf8',
    banner: { js: BANNER },
    logLevel,
    write,
  })
}

async function main () {
  try {
    const r = await buildPaginator({ logLevel: 'info' })
    if (r.warnings && r.warnings.length > 0) {
      console.warn(`paginator 构建有 ${r.warnings.length} 条告警`)
    }
  } catch (error) {
    console.error('paginator 构建失败：', error)
    process.exitCode = 1
  }
}

if (require.main === module) main()

module.exports = {
  DESKTOP_ROOT,
  REPO_ROOT,
  ENTRY_FILE,
  OUTPUT_FILE,
  GLOBAL_NAME,
  BANNER,
  buildPaginator,
}
