#!/usr/bin/env node
/**
 * extract-evasions.js — 从 puppeteer-extra-plugin-stealth（MIT）提取 stealth evasions 页面侧源码
 *
 * 契约（PRD v3.2 §3.1，评审 F8）：
 * - **单一真源 = npm 包版本**（本脚本只做提取，不手编 bundle）
 * - 产物 apps/desktop/electron/services/stealth/evasions-bundle.js 是防回归快照
 *   （sha256 由 evasions.test.js 锁定；上游升级后重跑本脚本 + 显式重录快照）
 *
 * 两种提取形态（2026-10-14 实测修正：naive fn.toString() 会抓到 withUtils 包装器而非
 * 真实载荷——包装器在页面 scope 必抛 ReferenceError）：
 *   A. **withUtils 包装形态**（chrome.runtime / navigator.permissions / …）：
 *      onPageCreated 经 withUtils(page).evaluateOnNewDocument(mainFn, opts) 调用，
 *      捕获到的是 `({_utilsFns,_mainFunction,_args}) => …` 包装器 + 载荷对象；
 *      重构为自包含 IIFE（与上游 extract-stealth-evasions、social-auto-upload 的
 *      stealth.min.js 同形态）：物化 utils → eval(_mainFunction)(utils, ..._args)
 *   B. **直连形态**（navigator.webdriver / window.outerdimensions）：
 *      onPageCreated 直接 page.evaluateOnNewDocument(fn)，转成立即执行 `(${fn})()`
 *
 * 用法：
 *   node scripts/extract-evasions.js            # 生成/更新 bundle
 *   node scripts/extract-evasions.js --check    # 只校验 bundle 与当前包版本一致（CI 用）
 */
'use strict'

const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')

const ROOT = path.join(__dirname, '..')
const PKG = 'puppeteer-extra-plugin-stealth'

// 最小集（PRD §3.1；模块名 = evasions/ 目录名）
const MINIMUM_SET = [
  'navigator.webdriver',
  'chrome.runtime',
  'navigator.permissions',
  'navigator.plugins',
  'navigator.languages',
  'iframe.contentWindow',
  'window.outerdimensions',
]

const OUT = path.join(ROOT, 'apps/desktop/electron/services/stealth/evasions-bundle.js')

function resolvePkg () {
  const candidates = [
    path.join(ROOT, 'node_modules', PKG),
    path.join(ROOT, 'apps/desktop/node_modules', PKG),
  ]
  for (const c of candidates) {
    if (fs.existsSync(c)) return c
  }
  throw new Error(`${PKG} not found in hoisted locations; run pnpm install first`)
}

/** 把 withUtils 包装形态重构成自包含 IIFE（extract-stealth-evasions 同款） */
function reconstructWrapped (payload) {
  const runner = [
    '(({_utilsFns, _mainFunction, _args}) => {',
    '  const utils = Object.fromEntries(Object.entries(_utilsFns).map(([key, value]) => [key, eval(value)]));', // eslint-disable-line no-eval
    '  utils.init();',
    '  return eval(_mainFunction)(utils, ..._args);', // eslint-disable-line no-eval
    '})',
  ].join('\n')
  return runner + '(' + JSON.stringify(payload) + ')'
}

function extractOne (name) {
  const modPath = path.join(resolvePkg(), 'evasions', name)
  const factory = require(modPath)
  const plugin = factory({})
  if (typeof plugin.onPageCreated !== 'function') {
    throw new Error(`evasion ${name} has no onPageCreated (unexpected for minimum set)`)
  }
  const captured = []
  const fakePage = {
    evaluateOnNewDocument: async (fn, ...args) => {
      if (typeof fn !== 'function') throw new Error(`evasion ${name}: arg not a function`)
      captured.push({ fn, args })
    },
  }
  return Promise.resolve(plugin.onPageCreated(fakePage)).then(() => {
    if (captured.length === 0) throw new Error(`evasion ${name}: nothing captured`)
    const codes = captured.map(({ fn, args }) => {
      const src = fn.toString()
      const isWrapper = /_utilsFns/.test(src) && /_mainFunction/.test(src)
      if (isWrapper) {
        const payload = args && args[0]
        if (!payload || typeof payload._mainFunction !== 'string') {
          throw new Error(`evasion ${name}: wrapper detected but payload missing _mainFunction`)
        }
        return reconstructWrapped(payload)
      }
      // 直连形态：立即执行
      return `(${src})()`
    })
    return { name, code: codes.join('\n;\n') }
  })
}

function buildBundle (pkgVersion, entries) {
  const header = [
    '/* eslint-disable */',
    '// AUTO-GENERATED by scripts/extract-evasions.js — DO NOT EDIT BY HAND',
    `// Source: ${PKG}@${pkgVersion} (MIT License, Copyright (c) 2018-2024 berstend`,
    '//   https://github.com/berstend/puppeteer-extra/tree/master/packages/puppeteer-extra-plugin-stealth)',
    '// Extraction: onPageCreated -> evaluateOnNewDocument；withUtils 包装形态重构为自包含 IIFE',
    '// 快照锁见同目录 evasions.test.js（sha256 漂移即红；重录走 EVASIONS_SNAPSHOT_SHA256）',
    '',
  ].join('\n')
  const evasions = {}
  for (const e of entries) evasions[e.name] = { name: e.name, code: e.code }
  return (
    header +
    "'use strict'\n\n" +
    'const evasions = ' + JSON.stringify(evasions, null, 2) + '\n\n' +
    'module.exports = { evasions, source: ' + JSON.stringify({ pkg: PKG, version: pkgVersion }) + ' }\n'
  )
}

async function main () {
  const checkOnly = process.argv.includes('--check')
  const pkgJson = require(path.join(resolvePkg(), 'package.json'))
  const entries = []
  for (const name of MINIMUM_SET) {
    entries.push(await extractOne(name))
  }
  const bundle = buildBundle(pkgJson.version, entries)
  const hash = crypto.createHash('sha256').update(bundle, 'utf8').digest('hex')

  if (checkOnly) {
    if (!fs.existsSync(OUT)) {
      console.error(`[extract-evasions] bundle missing: ${OUT}`)
      process.exit(1)
    }
    const currentHash = crypto.createHash('sha256').update(fs.readFileSync(OUT, 'utf8'), 'utf8').digest('hex')
    if (currentHash !== hash) {
      console.error(`[extract-evasions] bundle 漂移：磁盘 ${currentHash.slice(0, 12)} vs 包版本 ${hash.slice(0, 12)}`)
      console.error('  若为有意的上游升级：node scripts/extract-evasions.js 后重录快照常量')
      process.exit(1)
    }
    console.log(`[extract-evasions] OK: ${PKG}@${pkgJson.version}, sha256=${hash.slice(0, 12)}`)
    return
  }

  fs.mkdirSync(path.dirname(OUT), { recursive: true })
  fs.writeFileSync(OUT, bundle)
  console.log(`[extract-evasions] wrote ${path.relative(ROOT, OUT)}`)
  console.log(`[extract-evasions] source: ${PKG}@${pkgJson.version}`)
  console.log(`[extract-evasions] sha256=${hash}`)
  console.log('[extract-evasions] 下一步：把该 sha256 填进 evasions.test.js 的 SNAPSHOT_SHA256 常量')
}

main().catch((e) => {
  console.error(`[extract-evasions] FAILED: ${e.message}`)
  process.exit(1)
})
