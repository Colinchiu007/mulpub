/**
 * 运行时下发的「重启生效」提示 —— 单一真源（2026-10-17）
 *
 * PRD：ops-center/docs/PRD-ops-center-restart-hint.md
 *
 * 为什么需要它
 * ------------
 * 桌面端 OpsCenterSync **只在应用启动时同步一次**（ops-center-sync.js:748
 * autoSyncOnStart，setTimeout 3000ms，仅此一次；全文件无 setInterval）。
 * 所以运营中心改完配置后，已启动的应用不会重拉 —— 运营者看到「改了没反应」，
 * 会反复保存、甚至回滚自己的正确配置。
 *
 * 「需重启才生效」是当前实现的**预期行为**（MpSidebar.vue:126-127 注释：
 * 「运营侧改动在客户端下次启动同步后自动可见」），但界面上没有任何地方说明。
 *
 * 本 PRD 的做法：保存成功后加一句诚实的提示。刻意**不**做：
 *   - 不加定时同步/轮询 —— 单站点场景属过度设计，且带来备份/升级/权限三份额外维护面；
 *   - 不加「立即同步」按钮 —— ops-center-sync-autosync-guard.js 注明「运营同步对用户
 *     透明：配置卡片已隐藏」，加按钮破坏该契约。
 *
 * 为什么文案必须是常量
 * ------------------
 * 一次要改 6 个下发页面。各写一遍的后果：① 文案漂移；② 单测要写 6 条重复断言；
 * ③ 将来口径变化（例如真的加了定时同步）要改 6 处。故收敛为单一真源，
 * 并由 restart-hint.test.js 的 C1 结构锁保证「字面量不得出现第二次」。
 *
 * 为什么拆成两个语义段（WHEN / HOW）
 * ---------------------------------
 * 首版把两个语义挤在一句里：「已保存，将在应用下次启动时生效；如需立即生效请重启桌面应用」。
 * 变异 MR2 抓到问题：删掉前半句的「生效」后，后半句仍含「生效」，断言**抓不到** ——
 * 即「何时生效」这个语义可以被静默删掉。拆成两段后，两个语义各自可独立断言。
 */

/** 「何时生效」：说明本次改动的生效时机（应用下次启动）。 */
export const RESTART_HINT_WHEN = '将在应用下次启动时生效'

/** 「如何让它立刻生效」：给出明确动作，且指明重启的是桌面应用而非运营中心。 */
export const RESTART_HINT_HOW = '如需立即生效请重启桌面应用'

/** 完整提示 = 两段拼接。 */
export const RESTART_HINT = RESTART_HINT_WHEN + '；' + RESTART_HINT_HOW

/**
 * 提示停留时长（ms）。
 *
 * 为什么不是 Element Plus 默认的 3000：新文案约 40 个汉字，按中文阅读速度
 * （约 5 字/秒）需 8 秒。3000ms 会让多数人读不完就消失，等于没提示。
 * 6000ms 是「多数人能读完」与「不长时间挡屏」的折中；该下界由测试锁定，
 * 防止后人调回默认值。
 */
export const RESTART_HINT_DURATION = 6000

/**
 * 是否该在本轮结果上附加「重启生效」提示。
 *
 * fail-closed：只有**明确成功**才提示。失败路径、异常路径、未知结果一律不提示 ——
 * 在保存失败时说「已保存，重启后生效」是最严重的误导。
 *
 * @param {{ok?: boolean}|null|undefined} result 保存结果
 * @returns {boolean}
 */
export function shouldShowRestartHint (result) {
  return Boolean(result && result.ok === true)
}
